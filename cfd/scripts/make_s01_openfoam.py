"""Generate OpenFOAM cases for S01: steady laminar Reynolds-number sweep (validation).

Target: OpenFOAM v2406 (openfoam.com / ESI), solver simpleFoam, laminar.
Fluid: ISO VG 32 oil, nu = mu/rho = 0.028/870 m^2/s.
Inlet: flowRateInletVelocity with Q = v_bulk * (discrete inlet area), so the bulk
velocity is exact on the polygonal cross-section.
Monitoring: area-averaged kinematic pressure on faceZones turn0..turnN (start of each turn).

Writes cfd/openfoam/s01/:
    mesh/constant/polyMesh   shared mesh (generated once by make_helix_mesh.py)
    re00100/ ... re04000/    one case per Re (0/, constant/, system/)
    Allrun                   bash script: copies the mesh, checkMesh, runs in parallel, logs

Usage (Windows or WSL):  python make_s01_openfoam.py [--skip-mesh]
GCI study:               python make_s01_openfoam.py --mesh coarse --re 100 1000 4000
                         python make_s01_openfoam.py --mesh fine   --re 100 1000 4000
"""
import argparse
import json
import os
import subprocess
import sys

RE_LIST = [100, 250, 500, 1000, 2000, 4000]
RHO, MU = 870.0, 0.028
NU = MU / RHO
ITER = 4000

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.normpath(os.path.join(here, '..', 'openfoam', 's01'))

HDR = """/*--------------------------------*- C++ -*----------------------------------*\\
| Helical fluid inerter - case S01 (generated by make_s01_openfoam.py)        |
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    object      {obj};
}}

"""


def write(path, cls, obj, body):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', newline='\n') as fh:
        fh.write(HDR.format(cls=cls, obj=obj) + body)


def turn_monitors(n_planes):
    out = []
    for i in range(n_planes):
        out.append(f"""    pTurn{i}
    {{
        type            surfaceFieldValue;
        libs            (fieldFunctionObjects);
        log             false;
        writeControl    timeStep;
        writeInterval   1;
        writeFields     false;
        regionType      faceZone;
        name            turn{i};
        operation       areaAverage;
        fields          (p);
    }}
""")
    return ''.join(out)


def make_case(re_num, info):
    v = re_num * NU / info['d']
    Q = v * info['inlet_area']
    case = os.path.join(root, f're{re_num:05d}')
    write(os.path.join(case, '0', 'U'), 'volVectorField', 'U', f"""dimensions      [0 1 -1 0 0 0 0];
internalField   uniform (0 0 0);

boundaryField
{{
    inlet
    {{
        type                flowRateInletVelocity;
        volumetricFlowRate  constant {Q:.10e};   // v_bulk = {v:.6f} m/s, Re = {re_num}
        value               uniform (0 0 0);
    }}
    outlet
    {{
        type            inletOutlet;
        inletValue      uniform (0 0 0);
        value           uniform (0 0 0);
    }}
    wall
    {{
        type            noSlip;
    }}
}}
""")
    write(os.path.join(case, '0', 'p'), 'volScalarField', 'p', """dimensions      [0 2 -2 0 0 0 0];   // kinematic pressure p/rho
internalField   uniform 0;

boundaryField
{
    inlet   { type zeroGradient; }
    outlet  { type fixedValue; value uniform 0; }
    wall    { type zeroGradient; }
}
""")
    write(os.path.join(case, 'constant', 'transportProperties'), 'dictionary', 'transportProperties',
          f"""transportModel  Newtonian;
nu              {NU:.8e};   // ISO VG 32 oil at 40 C: mu = {MU} Pa s, rho = {RHO} kg/m^3
""")
    write(os.path.join(case, 'constant', 'turbulenceProperties'), 'dictionary', 'turbulenceProperties',
          'simulationType  laminar;\n')
    n_planes = info['turns'] + 1
    write(os.path.join(case, 'system', 'controlDict'), 'dictionary', 'controlDict', f"""application     simpleFoam;
startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         {ITER};
deltaT          1;
writeControl    timeStep;
writeInterval   {ITER};
purgeWrite      0;
writeFormat     binary;
writePrecision  10;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable true;

functions
{{
    solverInfo
    {{
        type            solverInfo;
        libs            (utilityFunctionObjects);
        fields          (U p);
        writeResidualFields no;
    }}
    outletFlux
    {{
        type            surfaceFieldValue;
        libs            (fieldFunctionObjects);
        log             false;
        writeControl    timeStep;
        writeInterval   1;
        writeFields     false;
        regionType      patch;
        name            outlet;
        operation       sum;
        fields          (phi);
    }}
{turn_monitors(n_planes)}}}
""")
    write(os.path.join(case, 'system', 'fvSchemes'), 'dictionary', 'fvSchemes', """ddtSchemes      { default steadyState; }
gradSchemes     { default Gauss linear; }
divSchemes
{
    default         none;
    div(phi,U)      bounded Gauss linearUpwind grad(U);
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes        { default Gauss linear corrected; }
interpolationSchemes    { default linear; }
snGradSchemes           { default corrected; }
""")
    write(os.path.join(case, 'system', 'fvSolution'), 'dictionary', 'fvSolution', """solvers
{
    // Tuned for the long, thin helix (default GAMG needed ~350 iterations per step;
    // this setting needs ~2, about 14x faster overall in a benchmark on this mesh)
    p
    {
        solver          GAMG;
        smoother        DICGaussSeidel;
        agglomerator    faceAreaPair;
        mergeLevels     1;
        nCellsInCoarsestLevel 50;
        cacheAgglomeration true;
        tolerance       1e-10;
        relTol          0.05;
    }
    Phi     // potentialFoam initialisation
    {
        $p;
        tolerance       1e-8;
        relTol          0.01;
    }
    U
    {
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-12;
        relTol          0.1;
    }
}

potentialFlow
{
    nNonOrthogonalCorrectors 2;
}

SIMPLE
{
    nNonOrthogonalCorrectors 0;
    consistent      yes;
    residualControl
    {
        p       1e-7;
        U       1e-9;
    }
}

relaxationFactors
{
    equations { U 0.9; }
}
""")
    write(os.path.join(case, 'system', 'decomposeParDict'), 'dictionary', 'decomposeParDict',
          'numberOfSubdomains 4;\nmethod          scotch;\n')
    return v, Q


ALLRUN = r"""#!/bin/bash
# Run every S01 case:  ./Allrun [nProcs]      (default 4; use 1 for serial)
# Needs the OpenFOAM v2406 environment, e.g.:  source /usr/lib/openfoam/openfoam2406/etc/bashrc
cd "${0%/*}" || exit 1
NP=${1:-4}
command -v simpleFoam >/dev/null || { echo "OpenFOAM environment not loaded (simpleFoam not found)"; exit 1; }

for c in re*/; do
    c=${c%/}
    echo "=== $c ==="
    rm -rf "$c/constant/polyMesh" "$c"/processor* "$c/postProcessing"
    cp -r mesh/constant/polyMesh "$c/constant/"
    (
        cd "$c" || exit 1
        checkMesh > log.checkMesh 2>&1 || { echo "  checkMesh FAILED, see $c/log.checkMesh"; exit 1; }
        grep -q "Mesh OK" log.checkMesh && echo "  checkMesh: Mesh OK" || echo "  checkMesh: warnings, see log.checkMesh"
        if [ "$NP" -gt 1 ]; then
            foamDictionary -entry numberOfSubdomains -set "$NP" system/decomposeParDict > /dev/null
            decomposePar -force > log.decomposePar 2>&1
            mpirun -np "$NP" potentialFoam -initialiseUBCs -parallel > log.potentialFoam 2>&1
            mpirun -np "$NP" simpleFoam -parallel > log.simpleFoam 2>&1
            reconstructPar -latestTime > log.reconstructPar 2>&1
        else
            potentialFoam -initialiseUBCs > log.potentialFoam 2>&1
            simpleFoam > log.simpleFoam 2>&1
        fi
        tail -n 3 log.simpleFoam | sed 's/^/  /'
    )
done
echo "Done. Post-process with:  python ../../scripts/post_s01.py"
"""


MESH_LEVELS = {   # GCI study: refinement ratio ~1.33 in every direction
    'coarse': ['--n', '9', '--m', '9', '--per-turn', '75', '--leg-cells', '11'],
    'medium': [],  # make_helix_mesh.py defaults: n = m = 12, 100 per turn, 15 leg cells
    'fine':   ['--n', '16', '--m', '16', '--per-turn', '133', '--leg-cells', '20'],
}


def main():
    global root, ITER
    ap = argparse.ArgumentParser()
    ap.add_argument('--skip-mesh', action='store_true', help='reuse an existing mesh/')
    ap.add_argument('--mesh', choices=list(MESH_LEVELS), default='medium',
                    help='mesh level (medium = the baseline S01 set)')
    ap.add_argument('--re', type=int, nargs='+', default=RE_LIST, help='Reynolds numbers')
    ap.add_argument('--name', default=None,
                    help='output folder under cfd/openfoam/ (default s01, or gci_<mesh>)')
    args = ap.parse_args()
    name = args.name or ('s01' if args.mesh == 'medium' else f'gci_{args.mesh}')
    if args.mesh == 'fine':
        # converging cases need < 500 iterations; Re = 4000 never becomes steady on any mesh and is
        # averaged over its last 1000 iterations, so 2000 iterations (1.5 s each on 0.9M cells) suffice
        ITER = 2000
    root = os.path.normpath(os.path.join(here, '..', 'openfoam', name))
    mesh_case = os.path.join(root, 'mesh')
    if not args.skip_mesh:
        subprocess.run([sys.executable, '-I', os.path.join(here, 'make_helix_mesh.py'),
                        '--format', 'foam', '--out', mesh_case] + MESH_LEVELS[args.mesh], check=True)
    with open(os.path.join(mesh_case, 'mesh_info.json')) as fh:
        info = json.load(fh)
    for re_num in args.re:
        v, Q = make_case(re_num, info)
        print(f'Re = {re_num:5d}: v_bulk = {v:8.4f} m/s, Q = {Q:.4e} m^3/s')
    with open(os.path.join(root, 'Allrun'), 'w', newline='\n') as fh:
        fh.write(ALLRUN)
    print(f'Cases and Allrun written to {root}')


if __name__ == '__main__':
    main()
